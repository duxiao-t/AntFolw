-- 版本的「变更说明」：导入时顺手写一句人话，说明这一版改了什么。
--
-- 为什么要有它：版本号本身（v3 → v4）说明不了任何事，维护人下次打开只看到两个数字；
-- 关掉了哪几个选项、加了什么分类，只有写这句话的人知道。它和「版本对比」互补——
-- 对比回答"差在哪"，说明回答"为什么差"。
--
-- 随版本不可变（不提供编辑入口）：说明和它描述的那份行数据是同一时刻的快照，
-- 允许事后改会变成"数据是 v3、解释是后来补的"。
ALTER TABLE t_option_data_source_version
    ADD COLUMN IF NOT EXISTS note VARCHAR(200);
